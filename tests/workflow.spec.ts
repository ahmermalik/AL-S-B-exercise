import { test, expect, type Page, type BrowserContext } from "@playwright/test";
import type { CaseDetail, Operations, Workspace, PackageDraft } from "../src/shared/types";
const origin = "http://127.0.0.1:3101";
async function login(page: Page, role: "manager" | "accountant") {
  await page.goto("/login"); await page.getByLabel("Email", { exact: true }).fill(`${role}@assetliving.com`);
  await page.getByLabel("Password", { exact: true }).fill("CloseReview!2026");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Close workspace", exact: true })).toBeVisible();
}
async function readCase(context: BrowserContext, id: string): Promise<CaseDetail> {
  const r = await context.request.get(`${origin}/api/cases/${id}`); expect(r.ok()).toBeTruthy(); return r.json();
}
async function action(context: BrowserContext, id: string, input: Record<string, unknown>) {
  const { resetGeneration } = await (await context.request.get(`${origin}/api/reset`)).json();
  return context.request.post(`${origin}/api/cases/${id}/actions`, { data: input, headers: { Origin: origin, "X-Workspace-Generation": resetGeneration } });
}

